func TestProjectListGetHelpSurface(t *testing.T) {
	if !strings.Contains(projectCmd.Long, "project list") {
		t.Fatalf("project Long should mention project list: %s", projectCmd.Long)
	}
	var hasList, hasGet bool
	for _, c := range projectCmd.Commands() {
		switch c.Name() {
		case "list":
			hasList = true
		case "get":
			hasGet = true
		}
	}
	if !hasList || !hasGet {
		t.Fatalf("expected list+get, got list=%v get=%v", hasList, hasGet)
	}
}

func TestProjectListDryRun(t *testing.T) {
	var hits int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
		w.WriteHeader(500)
	}))
	t.Cleanup(srv.Close)

	t.Setenv(config.EnvAccessToken, "test-token-project-list-not-real")
	t.Setenv(config.EnvOrganizationID, "org-project-list")
	t.Setenv(config.EnvEdition, "central")
	t.Setenv(config.EnvAPIBaseURL, srv.URL)
	t.Setenv("YUNXIAO_PROFILE", "")

	stdout := withCmdJSONCapture(t)
	resetStringFlags(t, projectListCmd, "name")
	rootCmd.SetArgs([]string{"project", "list", "--name", "play", "--dry-run"})
	t.Cleanup(func() { rootCmd.SetArgs(nil) })

	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("execute: %v\n%s", err, stdout.String())
	}
	var env output.Envelope
	if err := json.Unmarshal(stdout.Bytes(), &env); err != nil {
		t.Fatalf("json: %v / %s", err, stdout.Bytes())
	}
	if !env.OK || !env.DryRun {
		t.Fatalf("%+v", env)
	}
	raw, _ := json.Marshal(env.Request)
	var req map[string]any
	_ = json.Unmarshal(raw, &req)
	url, _ := req["url"].(string)
	if !strings.Contains(url, "/projects:search") {
		t.Fatalf("url=%q", url)
	}
	if req["method"] != "POST" {
		t.Fatalf("method=%v", req["method"])
	}
	if hits != 0 {
		t.Fatalf("hits=%d", hits)
	}
}

