func TestPipelineJobHelpSurface(t *testing.T) {
	var hasLog, hasStop bool
	for _, c := range pipelineJobCmd.Commands() {
		switch c.Name() {
		case "log":
			hasLog = true
		case "stop":
			hasStop = true
		}
	}
	if !hasLog || !hasStop {
		t.Fatalf("pipeline job expected log+stop, log=%v stop=%v", hasLog, hasStop)
	}
	if !strings.Contains(pipelineJobStopCmd.Long, "high-risk-write") {
		t.Fatalf("job stop Long should mention high-risk-write: %s", pipelineJobStopCmd.Long)
	}
}

func TestPipelineJobLogDryRun(t *testing.T) {
	var hits int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
		w.WriteHeader(500)
	}))
	t.Cleanup(srv.Close)

	t.Setenv(config.EnvAccessToken, "test-token-pipeline-job-log-not-real")
	t.Setenv(config.EnvOrganizationID, "org-pipeline-job-log")
	t.Setenv(config.EnvEdition, "central")
	t.Setenv(config.EnvAPIBaseURL, srv.URL)
	t.Setenv("YUNXIAO_PROFILE", "")

	stdout := withCmdJSONCapture(t)
	resetStringFlags(t, pipelineJobLogCmd, "pipeline-id", "run-id", "job-id")
	rootCmd.SetArgs([]string{
		"pipeline", "job", "log",
		"--pipeline-id", "pipe-7",
		"--run-id", "run-9",
		"--job-id", "job-3",
		"--dry-run",
	})
	t.Cleanup(func() { rootCmd.SetArgs(nil) })

	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("execute: %v\n%s", err, stdout.String())
	}
	var env output.Envelope
	if err := json.Unmarshal(stdout.Bytes(), &env); err != nil {
		t.Fatalf("json: %v / %s", err, stdout.Bytes())
	}
	if !env.OK || !env.DryRun {
		t.Fatalf("%+v", env)
	}
	raw, _ := json.Marshal(env.Request)
	var req map[string]any
	_ = json.Unmarshal(raw, &req)
	url, _ := req["url"].(string)
	if !strings.Contains(url, "/pipelines/pipe-7/runs/run-9/job/job-3/log") {
		t.Fatalf("url=%q", url)
	}
	if req["method"] != "GET" {
		t.Fatalf("method=%v", req["method"])
	}
	if hits != 0 {
		t.Fatalf("hits=%d", hits)
	}
}

