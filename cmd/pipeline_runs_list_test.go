func TestPipelineRunsHelpSurface(t *testing.T) {
	var hasList, hasLatest, hasGet bool
	for _, c := range pipelineRunCmd.Commands() {
		switch c.Name() {
		case "list":
			hasList = true
		case "latest":
			hasLatest = true
		case "get":
			hasGet = true
		}
	}
	if !hasList || !hasLatest || !hasGet {
		t.Fatalf("expected run list+latest+get, got list=%v latest=%v get=%v", hasList, hasLatest, hasGet)
	}
	if !strings.Contains(pipelineRunListCmd.Long, "Risk: read") {
		t.Fatalf("run list Long should mention Risk: read: %s", pipelineRunListCmd.Long)
	}
}

func TestPipelineRunListDryRun(t *testing.T) {
	var hits int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
		w.WriteHeader(500)
	}))
	t.Cleanup(srv.Close)

	t.Setenv(config.EnvAccessToken, "test-token-pipe-run-list-not-real")
	t.Setenv(config.EnvOrganizationID, "org-pipe-run-list")
	t.Setenv(config.EnvEdition, "central")
	t.Setenv(config.EnvAPIBaseURL, srv.URL)
	t.Setenv("YUNXIAO_PROFILE", "")

	stdout := withCmdJSONCapture(t)
	resetStringFlags(t, pipelineRunListCmd, "pipeline-id", "status", "sort")
	rootCmd.SetArgs([]string{"pipeline", "run", "list", "--pipeline-id", "pipe-99", "--status", "RUNNING", "--dry-run"})
	t.Cleanup(func() { rootCmd.SetArgs(nil) })

	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("execute: %v\n%s", err, stdout.String())
	}
	var env output.Envelope
	if err := json.Unmarshal(stdout.Bytes(), &env); err != nil {
		t.Fatalf("json: %v / %s", err, stdout.Bytes())
	}
	if !env.OK || !env.DryRun {
		t.Fatalf("%+v", env)
	}
	raw, _ := json.Marshal(env.Request)
	var req map[string]any
	_ = json.Unmarshal(raw, &req)
	url, _ := req["url"].(string)
	if !strings.Contains(url, "/pipelines/pipe-99/runs") {
		t.Fatalf("url=%q", url)
	}
	if req["method"] != "GET" {
		t.Fatalf("method=%v", req["method"])
	}
	if !strings.Contains(url, "status=RUNNING") {
		t.Fatalf("want status query: %q", url)
	}
	if hits != 0 {
		t.Fatalf("hits=%d", hits)
	}
}

