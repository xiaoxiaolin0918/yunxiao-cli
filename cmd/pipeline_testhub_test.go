func TestPipelineHelpSurface(t *testing.T) {
	h := pipelineCmd.Long
	if !strings.Contains(h, "high-risk-write") {
		t.Fatalf("pipeline Long should mention high-risk-write: %s", h)
	}
	if !strings.Contains(h, "run cancel") && !strings.Contains(h, "cancel") {
		t.Fatalf("pipeline Long should mention cancel: %s", h)
	}
	var hasList, hasGet, hasRun bool
	for _, c := range pipelineCmd.Commands() {
		switch c.Name() {
		case "list":
			hasList = true
		case "get":
			hasGet = true
		case "run":
			hasRun = true
		}
	}
	if !hasList || !hasGet || !hasRun {
		t.Fatalf("expected list/get/run, got list=%v get=%v run=%v", hasList, hasGet, hasRun)
	}
}

