func TestPipelineVMDeployHelpSurface(t *testing.T) {
	h := pipelineVMDeployCmd.Long
	if !strings.Contains(h, "vm-deploy") && !strings.Contains(h, "deploy") {
		t.Fatalf("vm-deploy Long should mention deploy: %s", h)
	}
	if !strings.Contains(h, "high-risk-write") {
		t.Fatalf("vm-deploy Long should mention high-risk-write: %s", h)
	}
	var hasGet, hasStop, hasMachine bool
	for _, c := range pipelineVMDeployCmd.Commands() {
		switch c.Name() {
		case "get":
			hasGet = true
		case "stop":
			hasStop = true
		case "machine":
			hasMachine = true
		}
	}
	if !hasGet || !hasStop || !hasMachine {
		t.Fatalf("expected get/stop/machine, got get=%v stop=%v machine=%v", hasGet, hasStop, hasMachine)
	}
}

func TestPipelineVMDeployGetDryRun(t *testing.T) {
	var hits int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
		w.WriteHeader(500)
	}))
	t.Cleanup(srv.Close)

	t.Setenv(config.EnvAccessToken, "test-token-vm-deploy-get-not-real")
	t.Setenv(config.EnvOrganizationID, "org-vm-deploy-get")
	t.Setenv(config.EnvEdition, "central")
	t.Setenv(config.EnvAPIBaseURL, srv.URL)
	t.Setenv("YUNXIAO_PROFILE", "")

	stdout := withCmdJSONCapture(t)
	resetStringFlags(t, pipelineVMDeployGetCmd, "pipeline-id", "deploy-id")
	rootCmd.SetArgs([]string{
		"pipeline", "vm-deploy", "get",
		"--pipeline-id", "pipe-1",
		"--deploy-id", "dep-9",
		"--dry-run",
	})
	t.Cleanup(func() { rootCmd.SetArgs(nil) })

	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("execute: %v\n%s", err, stdout.String())
	}
	var env output.Envelope
	if err := json.Unmarshal(stdout.Bytes(), &env); err != nil {
		t.Fatalf("json: %v / %s", err, stdout.Bytes())
	}
	if !env.OK || !env.DryRun {
		t.Fatalf("%+v", env)
	}
	raw, _ := json.Marshal(env.Request)
	var req map[string]any
	_ = json.Unmarshal(raw, &req)
	url, _ := req["url"].(string)
	if !strings.Contains(url, "/pipelines/pipe-1/deploy/dep-9") {
		t.Fatalf("url=%q", url)
	}
	if req["method"] != "GET" {
		t.Fatalf("method=%v", req["method"])
	}
	if hits != 0 {
		t.Fatalf("hits=%d", hits)
	}
}

