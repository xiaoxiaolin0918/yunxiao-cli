func TestWorkitemMetaHelpSurface(t *testing.T) {
	var hasFields, hasWorkflow, hasActivities bool
	for _, c := range workitemCmd.Commands() {
		switch c.Name() {
		case "fields":
			hasFields = true
		case "workflow":
			hasWorkflow = true
		case "activities":
			hasActivities = true
		}
	}
	if !hasFields || !hasWorkflow || !hasActivities {
		t.Fatalf("expected fields+workflow+activities, got fields=%v workflow=%v activities=%v", hasFields, hasWorkflow, hasActivities)
	}
	if !strings.Contains(workitemFieldsCmd.Long, "Risk: read") {
		t.Fatalf("fields Long should mention Risk: read: %s", workitemFieldsCmd.Long)
	}
}

func TestWorkitemFieldsDryRun(t *testing.T) {
	var hits int
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		hits++
		w.WriteHeader(500)
	}))
	t.Cleanup(srv.Close)

	t.Setenv(config.EnvAccessToken, "test-token-wi-fields-not-real")
	t.Setenv(config.EnvOrganizationID, "org-wi-fields")
	t.Setenv(config.EnvEdition, "central")
	t.Setenv(config.EnvAPIBaseURL, srv.URL)
	t.Setenv("YUNXIAO_PROFILE", "")

	stdout := withCmdJSONCapture(t)
	resetStringFlags(t, workitemFieldsCmd, "space-id", "type-id")
	rootCmd.SetArgs([]string{"workitem", "fields", "--space-id", "space-1", "--type-id", "type-req", "--dry-run"})
	t.Cleanup(func() { rootCmd.SetArgs(nil) })

	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("execute: %v\n%s", err, stdout.String())
	}
	var env output.Envelope
	if err := json.Unmarshal(stdout.Bytes(), &env); err != nil {
		t.Fatalf("json: %v / %s", err, stdout.Bytes())
	}
	if !env.OK || !env.DryRun {
		t.Fatalf("%+v", env)
	}
	raw, _ := json.Marshal(env.Request)
	var req map[string]any
	_ = json.Unmarshal(raw, &req)
	url, _ := req["url"].(string)
	if !strings.Contains(url, "/projects/space-1/workitemTypes/type-req/fields") {
		t.Fatalf("url=%q", url)
	}
	if req["method"] != "GET" {
		t.Fatalf("method=%v", req["method"])
	}
	if hits != 0 {
		t.Fatalf("hits=%d", hits)
	}
}

